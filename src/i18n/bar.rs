//! Capture and search bar, command palette, tray menu, search filters, resurfacing reasons.

use super::common::{en_days, ru_days};

pub struct Bar {
    // Capture
    pub capture_hint: &'static str,
    /// Hover text of the lock icon shown when the text looks like a secret.
    pub secret_hover: &'static str,
    pub capture_keys: &'static str,
    /// The same with the latency of the last open, in ms.
    pub capture_keys_ms: fn(f64) -> String,

    // Search
    pub search_hint: &'static str,
    pub recent: &'static str,
    pub no_notes: &'static str,
    pub nothing_found: &'static str,
    /// Footer while a result's action strip is open.
    pub keys_actions: &'static str,
    pub keys_results: &'static str,
    /// From the number of results and the search time in ms.
    pub stats: fn(usize, f64) -> String,
    /// The same with the time the bar took to open, in ms.
    pub stats_opened: fn(usize, f64, f64) -> String,
    /// Badge on an archived result.
    pub archived_badge: &'static str,

    // Result actions
    pub act_open: &'static str,
    pub act_copy: &'static str,
    pub act_pin: &'static str,
    pub act_unpin: &'static str,
    pub act_archive: &'static str,
    /// The action on an already archived result.
    pub act_unarchive: &'static str,
    pub act_delete: &'static str,

    // Notices after an action
    pub copied_secret: &'static str,
    pub copy_failed: &'static str,
    pub copied: &'static str,
    pub pin_failed: &'static str,
    pub returned_to_layer: &'static str,
    pub archived: &'static str,
    pub archive_failed: &'static str,
    pub trashed: &'static str,
    pub delete_failed: &'static str,

    // Command palette
    pub commands_header: &'static str,
    /// From the number of commands and the time in ms.
    pub palette_stats: fn(usize, f64) -> String,
    pub no_command: &'static str,
    pub palette_footer: &'static str,
    /// Indexed like `commands::CommandId::ALL`.
    pub command_titles: [&'static str; 23],
    pub turn_off: &'static str,
    pub turn_on: &'static str,
    pub toggle: &'static str,
    pub hide_layer: &'static str,
    pub show_layer: &'static str,
    pub collapse_layer: &'static str,
    pub expand_layer: &'static str,
    pub unpin_card: &'static str,
    pub monitor_hint: &'static str,
    /// What the type commands put into the search: ideas, prompts, goals, reminders, links.
    /// Each ends with a space and is read back as a kind filter.
    pub filter_words: [&'static str; 5],

    // Tray menu
    pub hotkey_off: &'static str,
    pub hotkey_taken: &'static str,
    pub tray_capture: &'static str,
    pub tray_search: &'static str,
    pub tray_library: &'static str,
    pub tray_bottom: &'static str,
    pub tray_autostart: &'static str,
    pub tray_import: &'static str,
    pub tray_settings: &'static str,
    pub tray_exit: &'static str,

    // Date filters shown as chips: today, yesterday, this/last week, month, year
    pub periods: [&'static str; 8],
    /// "последние 7 дн" / "last 7 d".
    pub last_days: fn(i64) -> String,

    // Why a card came back
    pub reason_not_opened: &'static str,
    pub reason_wrote: fn(i64) -> String,
    pub reason_reminder_today: &'static str,
    pub reason_reminder_ago: fn(i64) -> String,
    // Snooze, lowercase (the menu capitalizes)
    pub snooze_tomorrow: &'static str,
    pub snooze_week: &'static str,
    pub snooze_month: &'static str,
    pub snooze_days: fn(i64) -> String,
}

